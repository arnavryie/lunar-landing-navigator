class TerrainSlopeAnalyzer:
    """Calculates local terrain gradients, aspect angles, and slope distributions from LOLA DEM matrices."""

    def __init__(self, pixel_scale_m: float = LOLA_POLAR_GRID_PIXEL_SCALE_M):
        self.pixel_scale = pixel_scale_m

    def compute_gradient(self, z_window_3x3: List[List[float]]) -> Tuple[float, float]:
        dz_dx = ((z_window_3x3[0][2] + 2 * z_window_3x3[1][2] + z_window_3x3[2][2]) -
                 (z_window_3x3[0][0] + 2 * z_window_3x3[1][0] + z_window_3x3[2][0])) / (8.0 * self.pixel_scale)
        dz_dy = ((z_window_3x3[2][0] + 2 * z_window_3x3[2][1] + z_window_3x3[2][2]) -
                 (z_window_3x3[0][0] + 2 * z_window_3x3[0][1] + z_window_3x3[0][2])) / (8.0 * self.pixel_scale)
        return dz_dx, dz_dy

    def slope_degrees(self, dz_dx: float, dz_dy: float) -> float:
        return math.degrees(math.atan(math.sqrt(dz_dx * dz_dx + dz_dy * dz_dy)))

    def aspect_degrees(self, dz_dx: float, dz_dy: float) -> float:
        aspect = math.degrees(math.atan2(dz_dy, -dz_dx))
        if aspect < 0.0:
            aspect += 360.0
        return aspect

    def classify_landing_slope_safety(self, slope_deg: float) -> str:
        if slope_deg <= 5.0:
            return "OPTIMAL_SAFE (<5°)"
        elif slope_deg <= 10.0:
            return "ACCEPTABLE (5-10°)"
        elif slope_deg <= 15.0:
            return "MARGINAL (10-15°)"
        else:
            return "HAZARDOUS (>15°)"


class RoughnessScorer:
    """Calculates root-mean-square roughness and Hurst exponent estimates."""

    def compute_rms_height(self, elevations: List[float]) -> float:
        if not elevations:
            return 0.0
        mean_elev = sum(elevations) / len(elevations)
        variance = sum((z - mean_elev) ** 2 for z in elevations) / len(elevations)
        return math.sqrt(variance)

    def compute_bidirectional_roughness(self, profile: List[float], step_m: float) -> float:
        if len(profile) < 2:
            return 0.0
        diffs = [abs(profile[i+1] - profile[i]) for i in range(len(profile)-1)]
        return (sum(diffs) / len(diffs)) / step_m


class VolatileSublimationModel:
    """Models sublimation loss rates for volatile species in lunar PSRs."""

    SPECIES_PARAMS = {
        "H2O": {"A": 3.5e12, "B": 6050.0},
        "CO2": {"A": 1.2e12, "B": 3120.0},
        "NH3": {"A": 2.1e12, "B": 3680.0},
        "CH4": {"A": 8.0e11, "B": 1150.0}
    }

    def sublimation_rate_kg_m2_s(self, species: str, temperature_k: float) -> float:
        params = self.SPECIES_PARAMS.get(species, self.SPECIES_PARAMS["H2O"])
        if temperature_k <= 0:
            return 0.0
        return params["A"] * math.exp(-params["B"] / temperature_k)

    def annual_loss_thickness_m(self, species: str, temperature_k: float, density_kg_m3: float = 930.0) -> float:
        rate = self.sublimation_rate_kg_m2_s(species, temperature_k)
        seconds_per_year = 365.25 * 86400.0
        annual_mass = rate * seconds_per_year
        return annual_mass / density_kg_m3


class LandingHazardClassifier:
    """Evaluates combined terrain risk for lunar lander touchdown zones."""

    def __init__(self, max_allowable_slope_deg: float = 12.0):
        self.max_slope = max_allowable_slope_deg

    def evaluate_ellipse(self, cell_slopes: List[float], cell_elevations: List[float]) -> Dict[str, Any]:
        if not cell_slopes:
            return {"safety_score": 0.0, "status": "NO_DATA"}
        safe_cells = sum(1 for s in cell_slopes if s <= self.max_slope)
        fraction_safe = safe_cells / len(cell_slopes)
        mean_slope = sum(cell_slopes) / len(cell_slopes)
        max_slope = max(cell_slopes)
        
        status = "SAFE" if fraction_safe >= 0.85 else ("MARGINAL" if fraction_safe >= 0.65 else "UNSAFE")
        return {
            "fraction_safe": round(fraction_safe, 4),
            "mean_slope_deg": round(mean_slope, 2),
            "max_slope_deg": round(max_slope, 2),
            "status": status,
            "safety_score": round(fraction_safe * 100.0, 1)
        }

