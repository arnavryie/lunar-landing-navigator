class EphemerisTelemetryValidator:
    """Validates topocentric vectors against JPL Horizons reference tables."""

    def __init__(self, tolerance_arcsec: float = 5.0):
        self.tolerance_deg = tolerance_arcsec / 3600.0

    def compute_angular_separation(self, az1: float, el1: float, az2: float, el2: float) -> float:
        az1_r, el1_r = math.radians(az1), math.radians(el1)
        az2_r, el2_r = math.radians(az2), math.radians(el2)
        d_el = el2_r - el1_r
        d_az = az2_r - az1_r
        a = math.sin(d_el / 2.0)**2 + math.cos(el1_r) * math.cos(el2_r) * math.sin(d_az / 2.0)**2
        return math.degrees(2.0 * math.atan2(math.sqrt(a), math.sqrt(max(0.0, 1.0 - a))))

    def verify_vector_pair(self, computed_vec: EphemerisVector, reference_vec: EphemerisVector) -> Dict[str, Any]:
        sun_err = self.compute_angular_separation(
            computed_vec.sun_azimuth_deg, computed_vec.sun_elevation_deg,
            reference_vec.sun_azimuth_deg, reference_vec.sun_elevation_deg
        )
        earth_err = self.compute_angular_separation(
            computed_vec.earth_azimuth_deg, computed_vec.earth_elevation_deg,
            reference_vec.earth_azimuth_deg, reference_vec.earth_elevation_deg
        )
        passed = (sun_err <= self.tolerance_deg) and (earth_err <= self.tolerance_deg)
        return {
            "sun_error_deg": round(sun_err, 6),
            "earth_error_deg": round(earth_err, 6),
            "tolerance_deg": round(self.tolerance_deg, 6),
            "passed": passed
        }


class SolarPowerSimulationModel:
    """Simulates lander photovoltaic array power output under grazing south polar illumination."""

    def __init__(self, array_area_m2: float = 4.5, efficiency: float = SOLAR_CELL_EFFICIENCY_GAAS):
        self.area = array_area_m2
        self.eff = efficiency

    def calculate_incident_power(self, sun_elevation_deg: float, panel_tilt_deg: float = 90.0) -> float:
        if sun_elevation_deg <= 0.0:
            return 0.0
        cos_theta = math.cos(math.radians(sun_elevation_deg))
        direct_flux = SOLAR_FLUX_AM0_WM2 * max(0.0, cos_theta)
        return direct_flux * self.area * self.eff


class DSNCommunicationLinkModel:
    """Evaluates Direct-To-Earth (DTE) radio links with Goldstone, Madrid, and Canberra stations."""

    def __init__(self, min_earth_elevation_deg: float = DSN_MINIMUM_ELEVATION_DEG):
        self.min_elevation = min_earth_elevation_deg

    def is_link_available(self, earth_elevation_deg: float) -> bool:
        return earth_elevation_deg >= self.min_elevation

    def estimate_data_rate_kbps(self, earth_elevation_deg: float, carrier_frequency_ghz: float = 8.4) -> float:
        if not self.is_link_available(earth_elevation_deg):
            return 0.0
        base_rate = 512.0
        elevation_gain = min(2.0, 1.0 + (earth_elevation_deg - self.min_elevation) / 20.0)
        return base_rate * elevation_gain

